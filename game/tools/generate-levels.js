// Generates src/levels.js. Every level is checked by the solver, so each one is
// guaranteed winnable and its par (fewest possible moves) is known.
// Usage: node tools/generate-levels.js
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseLevel } from '../src/engine.js';
import { solve } from '../src/solver.js';

const COLORS = 'ABCDEF';

// Each tier sets board size, colours, balls per colour, wall density and the
// par range a level must land in. Tiers are played in order.
export const TIERS = [
  { count: 3, w: 4, h: 5, colors: 1, perColor: 1, walls: 0.1, par: [1, 2] },
  { count: 7, w: 5, h: 6, colors: 2, perColor: 1, walls: 0.12, par: [2, 4] },
  { count: 15, w: 6, h: 7, colors: 2, perColor: 2, walls: 0.14, par: [4, 6] },
  { count: 20, w: 6, h: 8, colors: 3, perColor: 1, walls: 0.15, par: [5, 8] },
  { count: 15, w: 7, h: 9, colors: 3, perColor: 2, walls: 0.15, par: [7, 11] },
];

// Small seeded random generator (mulberry32) so output is reproducible.
function makeRng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function randomMap(rng, tier) {
  const { w, h } = tier;
  const grid = Array.from({ length: h }, () => Array(w).fill('.'));
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) if (rng() < tier.walls) grid[y][x] = '#';
  }
  const free = [];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (grid[y][x] === '.') free.push([x, y]);
  const take = () => free.splice(Math.floor(rng() * free.length), 1)[0];
  for (let c = 0; c < tier.colors; c++) {
    for (let k = 0; k < tier.perColor; k++) {
      if (free.length < 2) return null;
      const [hx, hy] = take();
      grid[hy][hx] = COLORS[c].toLowerCase();
      const [bx, by] = take();
      grid[by][bx] = COLORS[c];
    }
  }
  return grid.map((row) => row.join(''));
}

export function generateLevels(seed = 20261102) {
  const rng = makeRng(seed);
  const levels = [];
  const seen = new Set();
  for (const tier of TIERS) {
    const tierLevels = [];
    let made = 0;
    let attempts = 0;
    while (made < tier.count) {
      if (++attempts > 200000) throw new Error(`Could not fill tier ${JSON.stringify(tier)}`);
      const map = randomMap(rng, tier);
      if (!map || seen.has(map.join('/'))) continue;
      const { board, state } = parseLevel(map);
      const solution = solve(board, state, 30000);
      if (!solution) continue;
      const par = solution.length;
      if (par < tier.par[0] || par > tier.par[1]) continue;
      seen.add(map.join('/'));
      tierLevels.push({ map, par, solution });
      made++;
    }
    // Easier levels first within each tier, so difficulty rises smoothly.
    levels.push(...tierLevels.sort((a, b) => a.par - b.par));
  }
  return levels;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const started = Date.now();
  const levels = generateLevels();
  const body = levels
    .map((l) => `  { par: ${l.par}, map: [\n${l.map.map((r) => `    '${r}',`).join('\n')}\n  ] },`)
    .join('\n');
  const out = `// Generated by tools/generate-levels.js. Do not edit by hand.\nexport const LEVELS = [\n${body}\n];\n`;
  const target = new URL('../src/levels.js', import.meta.url);
  writeFileSync(target, out);
  console.log(`Wrote ${levels.length} levels in ${Date.now() - started} ms`);
}
